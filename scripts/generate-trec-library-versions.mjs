import fs from 'node:fs';
import path from 'node:path';
import {
  PDFCheckBox,
  PDFDocument,
  PDFDropdown,
  PDFOptionList,
  PDFRadioGroup,
  PDFTextField,
} from 'pdf-lib';

const root = process.cwd();
const catalogSource = fs.readFileSync(path.join(root, 'lib/trec-forms-library.ts'), 'utf8');
const rowPattern = /\{ formFamily: '([^']+)', formNumber: '([^']+)', title: (?:'((?:\\'|[^'])*)'|"([^"]*)"), effectiveDate: '([^']+)', category: '[^']+', pdfUrl: '([^']+)', local: true \}/g;
const catalog = [...catalogSource.matchAll(rowPattern)].map((match) => ({
  formFamily: match[1],
  formNumber: match[2],
  title: (match[3] ?? match[4]).replaceAll("\\'", "'"),
  effectiveDate: match[5],
  pdfUrl: match[6],
}));

function fieldType(field) {
  if (field instanceof PDFTextField) return 'text';
  if (field instanceof PDFCheckBox) return 'checkbox';
  if (field instanceof PDFRadioGroup) return 'radio';
  if (field instanceof PDFDropdown || field instanceof PDFOptionList) return 'choice';
  return null;
}

const versions = [];
for (const item of catalog) {
  if (['20', '40', '49'].includes(item.formFamily)) continue;
  const pdfPath = path.join(root, 'public', item.pdfUrl);
  const document = await PDFDocument.load(fs.readFileSync(pdfPath));
  const pages = document.getPages();
  const fields = document.getForm().getFields().flatMap((field, index) => {
    const type = fieldType(field);
    if (!type) return [];
    const widget = field.acroField.getWidgets()[0];
    const page = widget ? pages.findIndex((candidate) => candidate.ref === widget.P()) + 1 : 1;
    return [{
      id: `trec_${item.formFamily.replace(/[^a-z0-9]/gi, '_')}_p${String(Math.max(page, 1)).padStart(2, '0')}_f${String(index + 1).padStart(3, '0')}`,
      page: Math.max(page, 1),
      index: index + 1,
      type,
      label: field.getName(),
      pdfFieldName: field.getName(),
    }];
  });
  versions.push({
    id: `built-in-trec-${item.formNumber.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    ...item,
    pageCount: document.getPageCount(),
    fields,
    pageSections: Object.fromEntries(
      Array.from({ length: document.getPageCount() }, (_, index) => [index + 1, `Official TREC page ${index + 1}`]),
    ),
    isActive: true,
    createdAt: `${item.effectiveDate}T00:00:00.000Z`,
  });
}

const output = `// Generated by scripts/generate-trec-library-versions.mjs. Do not edit by hand.
import type { TrecFormVersion } from './trec-form-versions';

export const GENERATED_TREC_FORM_VERSIONS: TrecFormVersion[] = ${JSON.stringify(versions, null, 2)};
`;
fs.writeFileSync(path.join(root, 'lib/trec-library-versions.generated.ts'), output);
console.log(`Generated ${versions.length} TREC form versions with ${versions.reduce((sum, version) => sum + version.fields.length, 0)} live controls.`);
